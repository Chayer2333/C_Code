/*
 * printf_format_demo.c
 *
 * 演示 printf 格式说明符：
 *     %[标志][宽度][.精度][长度]转换字符
 *
 * 编译：
 *     gcc -Wall -Wextra -o fmt printf_format_demo.c
 * 运行：
 *     ./fmt
 *
 * 说明：
 *   - 每一段先打印标题，再打印若干对比行。
 *   - 注释里给出了该行大致会输出的内容。
 *   - 有些宽度/精度用 * 动态传入，注释里会标出。
 */

#include <stdio.h>
#include <string.h>   /* 需要 strlen */

/* 小工具：打印一条分隔线，整行总宽度固定为 n，标题居中 */
static const char equals[] =
    "============================================================"
    "============================================================";

static void line(const char *title)
{
    const int n = 60;                       /* 整行总宽度，可改 */
    int len   = (int)strlen(title);         /* 标题长度 */
    int left  = (n - len) / 2;              /* 左边空格数 */
    int right = n - len - left;             /* 右边空格数，保证 left+len+right == n */

    printf("\n %.*s %s %.*s \n", left, equals, title, right, equals);
}

int main(void)
{
    /* =========================================================
     * 一、转换字符（conversion specifier）
     * ========================================================= */

    line("1. 转换字符 d i u o x X f e g c s p %%");

    /* %d / %i：有符号十进制整数，两者对 printf 几乎一样 */
    printf("%%d  -> %d\n", 42);
    printf("%%i  -> %i\n", -42);

    /* %u：无符号十进制整数 */
    printf("%%u  -> %u\n", 42u);

    /* %o：八进制，%x / %X：十六进制，大小写不同 */
    printf("%%o  -> %o\n", 255);     /* 377   */
    printf("%%x  -> %x\n", 255);     /* ff    */
    printf("%%X  -> %X\n", 255);     /* FF    */

    /* %f：定点小数，默认 6 位小数
     * %e：科学计数法，默认 6 位小数
     * %g：自动选择 %f 或 %e，并去掉多余 0
     */
    printf("%%f  -> %f\n", 3.1415926);
    printf("%%e  -> %e\n", 3.1415926);
    printf("%%g  -> %g\n", 3.1415926);

    /* %c：单个字符 */
    printf("%%c  -> %c\n", 'A');

    /* %s：字符串 */
    printf("%%s  -> %s\n", "hello");

    /* %p：指针地址，具体格式由实现决定 */
    int x = 0;
    printf("%%p  -> %p\n", (void *)&x);

    /* %%：输出一个百分号本身 */
    printf("%%%%  -> %%\n");

    /* =========================================================
     * 二、标志（flag）
     *     -  左对齐
     *     +  强制显示正负号
     *     空格  正数前留一个空格
     *     #  对 o/x/X 加前缀，对浮点强制小数点
     *     0  用 0 填充（默认右对齐）
     * ========================================================= */

    line("2. 标志 - + 空格 # 0");

    /* 默认右对齐，宽度 8，左边补空格 */
    printf("[%8d]\n", 42);        /* [      42] */

    /* '-' 左对齐，右边补空格 */
    printf("[%-8d]\n", 42);       /* [42      ] */

    /* '+' 强制显示正号，负数仍显示负号 */
    printf("[%+d] [%+d]\n", 42, -42);   /* [+42] [-42] */

    /* ' ' 正数前留一个空格，负数仍显示负号 */
    printf("[% d] [% d]\n", 42, -42);   /* [ 42] [-42] */

    /* '0' 用 0 填充，注意：0 和 - 同时用，0 会被 - 覆盖 */
    printf("[%08d]\n", 42);       /* [00000042] */
    printf("[%-08d]\n", 42);      /* [42      ]，- 优先，0 被忽略 */

    /* '#' 对八进制加前缀 0，对十六进制加前缀 0x / 0X */
    printf("[%#o] [%#x] [%#X]\n", 255, 255, 255);  /* [0377] [0xff] [0XFF] */

    /* '#' 对浮点强制保留小数点，即使小数部分为 0 */
    printf("[%f] [%#f]\n", 3.0, 3.0);  /* [3.000000] [3.000000] */

    /* 标志可以组合使用，顺序不重要，但推荐按 -+ #0 写 */
    printf("[%+08d]\n", 42);      /* [+0000042] */
    printf("[%+-8d]\n", 42);      /* [+42     ] */

    /* =========================================================
     * 三、宽度（width）
     *     数字：固定宽度
     *     *  ：宽度从参数里取
     * ========================================================= */

    line("3. 宽度：固定宽度 vs %*d");

    /* 固定宽度 6 */
    printf("[%6d]\n", 42);        /* [    42] */

    /* 宽度从参数取：第一个 6 是宽度，42 是要打印的值 */
    printf("[%*d]\n", 6, 42);     /* [    42] */

    /* 宽度为负数：等价于左对齐，且宽度取绝对值 */
    printf("[%*d]\n", -6, 42);    /* [42    ] */

    /* 宽度不够时不会截断，原样输出 */
    printf("[%3d]\n", 123456);    /* [123456] */

    /* 字符串同理 */
    printf("[%8s]\n", "abc");     /* [     abc] */
    printf("[%-8s]\n", "abc");    /* [abc     ] */
    printf("[%*s]\n", 8, "abc");  /* [     abc] */

    /* 用 %*s 打印 n 个空格：字符串为空，宽度为 n */
    printf("[%*s]\n", 5, "");     /* [     ] */

    /* =========================================================
     * 四、精度（.precision）
     *     对整数：最少位数，不够补 0
     *     对浮点：小数位数
     *     对字符串：最多输出多少个字符
     *     .* ：精度从参数里取
     * ========================================================= */

    line("4. 精度：整数 / 浮点 / 字符串");

    /* 整数：精度表示最少输出几位数字，不够前面补 0 */
    printf("[%.5d]\n", 42);       /* [00042] */
    printf("[%.5d]\n", -42);      /* [-00042] */

    /* 浮点：精度表示小数点后保留几位 */
    printf("[%.2f]\n", 3.14159);  /* [3.14] */
    printf("[%.0f]\n", 3.14159);  /* [3]    */

    /* 字符串：精度表示最多输出几个字符 */
    printf("[%.3s]\n", "Hello");  /* [Hel] */
    printf("[%.10s]\n", "Hello"); /* [Hello]，不会补空格 */

    /* 精度用 * 动态给：第一个 3 是精度，42 是值 */
    printf("[%.*d]\n", 5, 42);    /* [00042] */
    printf("[%.*s]\n", 3, "Hello");/* [Hel] */

    /* 精度为负数：相当于没有精度，被忽略 */
    printf("[%.*d]\n", -3, 42);   /* [42] */

    /* =========================================================
     * 五、宽度 + 精度 同时用
     *     顺序：%[*][.*]转换字符
     *     参数顺序：先宽度，再精度，最后值
     * ========================================================= */

    line("5. 宽度 + 精度：%*.*d / %*.*s");

    /* 宽度 8，精度 5，值 42 */
    printf("[%*.*d]\n", 8, 5, 42);        /* [   00042] */

    /* 宽度 8，精度 3，字符串 Hello */
    printf("[%*.*s]\n", 8, 3, "Hello");   /* [     Hel] */

    /* 左对齐 + 宽度 + 精度 */
    printf("[%-*.*s]\n", 8, 3, "Hello");  /* [Hel     ] */

    /* 精度超过字符串长度时，不会补字符，只按实际长度输出 */
    printf("[%*.*s]\n", 8, 10, "Hello");  /* [   Hello] */

    /* =========================================================
     * 六、长度修饰符（length modifier）
     *     hh  char
     *     h   short
     *     l   long / double（对 c 是宽字符）
     *     ll  long long
     *     z   size_t
     *     长度修饰符要和对应类型的参数匹配
     * ========================================================= */

    line("6. 长度修饰符 hh h l ll z");

    signed char      sc = -1;
    short            sh = -2;
    long             lo = -3L;
    long long        ll = -4LL;
    size_t           sz = 123u;

    printf("%%hhd -> %hhd\n", sc);
    printf("%%hd  -> %hd\n",  sh);
    printf("%%ld  -> %ld\n",  lo);
    printf("%%lld -> %lld\n", ll);
    printf("%%zu  -> %zu\n",  sz);

    /* 浮点：%f 默认是 double，%Lf 才是 long double */
    long double ld = 3.14159265358979L;
    printf("%%Lf  -> %.10Lf\n", ld);

    /* =========================================================
     * 七、综合对比表：同一组值，不同格式
     * ========================================================= */

    line("7. 综合对比");

    int v = 42;
    printf("原始值 v = %d\n\n", v);

    printf("%-12s -> [%d]\n",   "%d",      v);
    printf("%-12s -> [%8d]\n",  "%8d",     v);
    printf("%-12s -> [%-8d]\n", "%-8d",    v);
    printf("%-12s -> [%08d]\n", "%08d",    v);
    printf("%-12s -> [%+d]\n",  "%+d",     v);
    printf("%-12s -> [%+08d]\n","%+08d",   v);
    printf("%-12s -> [%.5d]\n", "%.5d",    v);
    printf("%-12s -> [%8.5d]\n","%8.5d",   v);
    printf("%-12s -> [%-8.5d]\n","%-8.5d", v);

    printf("\n");

    double pi = 3.14159265;
    printf("原始值 pi = %f\n\n", pi);

    printf("%-12s -> [%f]\n",    "%f",       pi);
    printf("%-12s -> [%.2f]\n",  "%.2f",     pi);
    printf("%-12s -> [%10.2f]\n","%10.2f",   pi);
    printf("%-12s -> [%-10.2f]\n","%-10.2f", pi);
    printf("%-12s -> [%010.2f]\n","%010.2f", pi);
    printf("%-12s -> [%+10.2f]\n","%+10.2f", pi);

    printf("\n");

    const char *s = "Hello";
    printf("原始值 s = \"%s\"\n\n", s);

    printf("%-12s -> [%s]\n",     "%s",       s);
    printf("%-12s -> [%10s]\n",   "%10s",     s);
    printf("%-12s -> [%-10s]\n",  "%-10s",    s);
    printf("%-12s -> [%.3s]\n",   "%.3s",     s);
    printf("%-12s -> [%10.3s]\n", "%10.3s",   s);
    printf("%-12s -> [%-10.3s]\n","%-10.3s",  s);
    printf("%-12s -> [%*.*s]\n",  "%*.*s",    10, 3, s);

    /* =========================================================
     * 八、常见坑
     * ========================================================= */

    line("8. 常见坑");

    /* 坑 1：格式串类型和参数类型不匹配，是未定义行为。
     * 下面这行故意注释掉，不要运行：
     *     printf("%d\n", 3.14);   // 错：%d 要 int，却给了 double
     *     printf("%s\n", 42);     // 错：%s 要 char*，却给了 int
     */

    /* 坑 2：宽度/精度的 * 参数必须是 int，且要放在值前面 */
    printf("[%*.*d]\n", 8, 5, 42);   /* 正确：宽度 8，精度 5 */
    /* printf("[%*.*d]\n", 8, 42, 5); // 错：顺序反了，行为不可预期 */

    /* 坑 3：精度对字符串不会截断后再补齐，只限制最大输出长度 */
    printf("[%10.3s]\n", "Hello");   /* [       Hel]，宽度 10，最多 3 字符 */

    /* 坑 4：0 和 - 同时用，- 优先，0 被忽略 */
    printf("[%-08d]\n", 42);         /* [42      ] */

    /* 坑 5：%f 默认是 double，%Lf 才是 long double */
    float  f  = 1.5f;
    double d  = 1.5;
    long double L = 1.5L;
    printf("%%f  float  -> %f\n",  (double)f); /* 传 float 会被提升为 double */
    printf("%%f  double -> %f\n",  d);
    printf("%%Lf long double -> %Lf\n", L);

    return 0;
}